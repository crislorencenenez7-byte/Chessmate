const { Pool } = require("pg");

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL is not configured.");
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: { rejectUnauthorized: false },
  max: 5,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 10000
});

pool.on("error", error => {
  console.error("Unexpected PostgreSQL pool error:", error.message);
});

async function initDb() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username VARCHAR(18) UNIQUE NOT NULL,
      password_hash TEXT NOT NULL,
      rating INTEGER NOT NULL DEFAULT 800,
      highest_rating INTEGER NOT NULL DEFAULT 800,
      wins INTEGER NOT NULL DEFAULT 0,
      losses INTEGER NOT NULL DEFAULT 0,
      draws INTEGER NOT NULL DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE IF NOT EXISTS matches (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      white_id BIGINT,
      black_id BIGINT,
      result TEXT NOT NULL,
      mode TEXT NOT NULL,
      white_rating_change INTEGER DEFAULT 0,
      black_rating_change INTEGER DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE INDEX IF NOT EXISTS users_leaderboard_idx
      ON users (rating DESC, wins DESC);

    CREATE INDEX IF NOT EXISTS matches_history_idx
      ON matches (id DESC);
  `);

  await pool.query(
    "ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE"
  );

  // Preserve existing admins and ensure both designated admins stay Admin.
  await pool.query(
    "UPDATE users SET is_admin = TRUE WHERE LOWER(username) IN (LOWER($1), LOWER($2))",
    ["CrisLorence", "josephsolo"]
  );

  const adminCheck = await pool.query(
    "SELECT id FROM users WHERE username = $1 AND is_admin = TRUE",
    ["CrisLorence"]
  );

  if (adminCheck.rows.length) {
    console.log("Admin account verified: CrisLorence.");
  } else {
    console.warn("ADMIN WARNING: CrisLorence account not found. No account was created.");
  }

  console.log("PostgreSQL tables are ready.");
}

module.exports = { pool, initDb };

// Admin-controlled application settings
async function initAdminSettings() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS app_settings (
      key TEXT PRIMARY KEY,
      value JSONB NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);
}

module.exports = { pool, initDb, initAdminSettings };
