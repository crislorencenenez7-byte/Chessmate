const { Pool } = require("pg");

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL is not configured.");
}

const databaseHost = new URL(process.env.DATABASE_URL).hostname;
const isLocalDatabase = ["localhost", "127.0.0.1", "::1"].includes(databaseHost);

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: isLocalDatabase ? false : { rejectUnauthorized: false },
  max: 5,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 10000
});

pool.on("error", error => {
  console.error("Unexpected PostgreSQL pool error:", error.message);
});

async function initDb() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username VARCHAR(18) UNIQUE NOT NULL,
      password_hash TEXT NOT NULL,
      rating INTEGER NOT NULL DEFAULT 800,
      highest_rating INTEGER NOT NULL DEFAULT 800,
      wins INTEGER NOT NULL DEFAULT 0,
      losses INTEGER NOT NULL DEFAULT 0,
      draws INTEGER NOT NULL DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE IF NOT EXISTS matches (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      white_id BIGINT,
      black_id BIGINT,
      result TEXT NOT NULL,
      mode TEXT NOT NULL,
      white_rating_change INTEGER DEFAULT 0,
      black_rating_change INTEGER DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE INDEX IF NOT EXISTS users_leaderboard_idx
      ON users (rating DESC, wins DESC);

    CREATE INDEX IF NOT EXISTS matches_history_idx
      ON matches (id DESC);
  `);

  await pool.query(
    "ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE"
  );

  // Preserve existing admins and ensure both designated admins stay Admin.
  await pool.query(
    "UPDATE users SET is_admin = TRUE WHERE LOWER(username) IN (LOWER($1), LOWER($2))",
    ["CrisLorence", "josephsolo"]
  );

  const adminCheck = await pool.query(
    "SELECT id FROM users WHERE username = $1 AND is_admin = TRUE",
    ["CrisLorence"]
  );

  if (adminCheck.rows.length) {
    console.log("Admin account verified: CrisLorence.");
  } else {
    console.warn("ADMIN WARNING: CrisLorence account not found. No account was created.");
  }


  // Diamonds, cosmetic inventory, player profiles, clans and tournament registrations.
  await pool.query(`
    ALTER TABLE users ADD COLUMN IF NOT EXISTS diamonds INTEGER NOT NULL DEFAULT 0;
    ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_key TEXT NOT NULL DEFAULT 'avatar_knight';
    ALTER TABLE users ADD COLUMN IF NOT EXISTS board_key TEXT NOT NULL DEFAULT 'classic';
    CREATE TABLE IF NOT EXISTS diamond_ledger (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      amount INTEGER NOT NULL,
      reason TEXT NOT NULL,
      reference TEXT UNIQUE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE IF NOT EXISTS topup_requests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      php_amount INTEGER NOT NULL CHECK (php_amount = 10),
      diamonds INTEGER NOT NULL CHECK (diamonds = 2),
      status TEXT NOT NULL DEFAULT 'pending',
      reference TEXT UNIQUE NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE IF NOT EXISTS cosmetic_purchases (
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      cosmetic_key TEXT NOT NULL,
      purchased_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      PRIMARY KEY(user_id, cosmetic_key)
    );
    CREATE TABLE IF NOT EXISTS clans (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(24) UNIQUE NOT NULL,
      invite_code VARCHAR(10) UNIQUE NOT NULL,
      leader_id BIGINT NOT NULL REFERENCES users(id),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE IF NOT EXISTS clan_members (
      clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
      user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
      joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      PRIMARY KEY(clan_id,user_id)
    );
    CREATE TABLE IF NOT EXISTS tournament_entries (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
      season TEXT NOT NULL DEFAULT 'open-season-1',
      registered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE(clan_id,season)
    );
    ALTER TABLE clans ADD COLUMN IF NOT EXISTS wins INTEGER NOT NULL DEFAULT 0;
    ALTER TABLE clans ADD COLUMN IF NOT EXISTS losses INTEGER NOT NULL DEFAULT 0;
    CREATE TABLE IF NOT EXISTS tournament_matches (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      season TEXT NOT NULL,
      round INTEGER NOT NULL,
      match_number INTEGER NOT NULL,
      clan_a_id BIGINT REFERENCES clans(id) ON DELETE SET NULL,
      clan_b_id BIGINT REFERENCES clans(id) ON DELETE SET NULL,
      winner_clan_id BIGINT REFERENCES clans(id) ON DELETE SET NULL,
      next_match_id BIGINT REFERENCES tournament_matches(id) ON DELETE SET NULL,
      next_slot CHAR(1),
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE(season,round,match_number)
    );
    CREATE INDEX IF NOT EXISTS tournament_matches_season_idx ON tournament_matches(season,round,match_number);
    CREATE TABLE IF NOT EXISTS tournament_entry_players (
      entry_id BIGINT NOT NULL REFERENCES tournament_entries(id) ON DELETE CASCADE,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      rating_at_registration INTEGER NOT NULL,
      PRIMARY KEY(entry_id,user_id)
    );
    INSERT INTO tournament_entry_players(entry_id,user_id,rating_at_registration)
      SELECT te.id,cm.user_id,u.rating FROM tournament_entries te
      JOIN clan_members cm ON cm.clan_id=te.clan_id JOIN users u ON u.id=cm.user_id
      WHERE NOT EXISTS (SELECT 1 FROM tournament_entry_players snap WHERE snap.entry_id=te.id)
      ON CONFLICT(entry_id,user_id) DO NOTHING;
  `);

  console.log("PostgreSQL tables are ready.");
}

module.exports = { pool, initDb };

// Admin-controlled application settings
async function initAdminSettings() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS app_settings (
      key TEXT PRIMARY KEY,
      value JSONB NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);
}

module.exports = { pool, initDb, initAdminSettings };
